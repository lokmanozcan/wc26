export function emptyHistory() {
  return { version: 1, snapshots: [] };
}

/** Seed verilerini bir kez ekle */
export function mergeSeedHistory(history) {
  const base = history?.snapshots?.length ? history : emptyHistory();
  const existingIds = new Set(base.snapshots.map((s) => s.id));
  const seedsToAdd = SEED_SNAPSHOTS.filter((s) => !existingIds.has(s.id));
  if (!seedsToAdd.length) return base;
  const merged = [...base.snapshots, ...seedsToAdd].sort((a, b) => a.recordedAt - b.recordedAt);
  return { version: 1, snapshots: merged };
}

export function snapshotFromSimResults(results, { label, simKey, recordedAt = Date.now() } = {}) {
  const teams = {};
  if (results?.teams) {
    Object.entries(results.teams).forEach(([id, t]) => {
      teams[id] = {
        r32: t.r32 ?? 0,
        r16: t.r16 ?? 0,
        qf: t.qf ?? 0,
        sf: t.sf ?? 0,
        f: t.f ?? 0,
        champion: t.champion ?? 0,
      };
    });
  }
  return {
    id: `live-${recordedAt}`,
    label: label || new Date(recordedAt).toLocaleString("tr-TR", { day: "2-digit", month: "short", hour: "2-digit", minute: "2-digit" }),
    recordedAt,
    simKey: simKey || null,
    isSeed: false,
    teams,
  };
}

/** Güncelle sonrası yeni nokta ekle */
export function appendProbabilitySnapshot(history, snapshot) {
  const base = history?.snapshots?.length ? history : emptyHistory();
  return {
    version: 1,
    snapshots: [...base.snapshots, snapshot].sort((a, b) => a.recordedAt - b.recordedAt),
  };
}

export function getTeamTrendSeries(snapshots, teamId, metricKey) {
  return snapshots
    .map((snap) => ({
      id: snap.id,
      label: snap.label,
      recordedAt: snap.recordedAt,
      value: snap.teams?.[teamId]?.[metricKey] ?? null,
      isSeed: !!snap.isSeed,
    }))
    .filter((p) => p.value !== null && p.value !== undefined);
}
